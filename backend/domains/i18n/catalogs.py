def message(key: str, locale: str = "id", **kwargs) -> str:
    catalog = CATALOGS.get(locale) or CATALOGS["id"]
    text = catalog.get(key) or CATALOGS["id"].get(key, key)
    if kwargs:
        for name, value in kwargs.items():
            text = text.replace("{" + name + "}", str(value))
    return text
