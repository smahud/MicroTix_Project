"""Independent review reproduction, outside product source.
Run from backend with its pytest.ini and PYTHONPATH=.; PostgreSQL only.
This simulates the durable post-success state produced by pre-PA006 code,
then retries the same logical proof submission on the new candidate.
"""
import pytest
from django.utils import timezone

from domains.common.idempotency import _body_hash
from domains.common.tenant_context import tenant_scope
from domains.jobs.models import IdempotencyKey
from domains.subscriptions import services as sub_services
from domains.subscriptions.models import PaymentSubmission
from tests.integration.test_idempotency_pa006 import (
    _setup_world, _client, _make_invoice, _make_submission, PNG_B64, pytestmark,
)


def test_review_upgrade_legacy_saas_proof_same_principal_replays_without_duplicate():
    sub_services.seed_plans()
    world = _setup_world('review-leg-proof')
    invoice = _make_invoice(world.tenant)
    original = _make_submission(world.tenant, invoice, world.owner)
    body = {'file_b64': PNG_B64, 'mime': 'image/png'}
    original_response = {'submission_id': str(original.id), 'state': original.state}
    # Exact scope generated by main@9903d9b for PaymentSubmissionView.
    # A real pre-upgrade successful request already committed its domain row.
    # Migration 0004 retains this record unchanged; only uniqueness changes.
    legacy = IdempotencyKey.objects.create(
        principal=str(world.owner.id),
        scope=f'payment_submission:{world.tenant.id}:',
        idem_key='upgrade-proof-key',
        body_hash=_body_hash(body),
        response_status=201,
        response_body=original_response,
        created_at=timezone.now(),
    )
    client = _client(world.owner, active_tenant=world.tenant.id)
    response = client.post(
        f'/api/v1/tenants/{world.tenant.id}/saas-invoices/{invoice.id}/payment-submissions',
        body,
        headers={'Idempotency-Key': 'upgrade-proof-key'},
    )
    assert response.status_code == 201, response.content
    with tenant_scope(world.tenant.id):
        persisted = list(PaymentSubmission.objects.filter(invoice=invoice).values_list('id', flat=True))
    assert response.json() == original_response and len(persisted) == 1, {
        'original': original_response, 'actual': response.json(),
        'submission_count': len(persisted),
        'legacy_record_preserved': IdempotencyKey.objects.filter(pk=legacy.pk).exists(),
        'idempotency_scopes': list(IdempotencyKey.objects.filter(idem_key='upgrade-proof-key').values_list('scope', flat=True)),
    }
